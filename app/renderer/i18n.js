  function normalize(locale) {
    return String(locale || '').toLowerCase().startsWith('en') ? 'en-US' : 'zh-CN';
  }
  let locale = normalize(localStorage.getItem(STORAGE_KEY) || navigator.language || DEFAULT_LOCALE);

  function t(key, vars) {
    const table = MESSAGES[locale] || MESSAGES[DEFAULT_LOCALE];
    let value = table[key] || MESSAGES[DEFAULT_LOCALE][key] || key;
    Object.keys(vars || {}).forEach((name) => {
      value = value.replace(new RegExp('\\{' + name + '\\}', 'g'), String(vars[name]));
    });
    return value;
  }

  function apply(root) {
    const scope = root || document;
    scope.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
    scope.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
    scope.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
    document.documentElement.lang = locale === 'en-US' ? 'en' : 'zh-CN';
    document.documentElement.dataset.locale = locale;
    document.querySelectorAll('[data-locale]').forEach((el) => {
      const active = normalize(el.dataset.locale) === locale;
      el.classList.toggle('active', active);
      el.setAttribute('aria-pressed', String(active));
    });
  }

  function setLocale(next) {
    const normalized = normalize(next);
    if (normalized === locale) return false;
    locale = normalized;
    localStorage.setItem(STORAGE_KEY, locale);
    apply();
    window.dispatchEvent(new CustomEvent('clay:locale-change', { detail: { locale } }));
    return true;
  }

  window.ClayI18n = { t, apply, setLocale, getLocale: () => locale, messages: MESSAGES };
  document.addEventListener('DOMContentLoaded', () => {
    apply();
    document.querySelectorAll('[data-locale]').forEach((el) => {
      el.addEventListener('click', () => setLocale(el.dataset.locale));
    });
    if (window.clay && window.clay.setLocale) window.clay.setLocale(locale);
  });
